"""감시 대상 목적지 목록.

거리는 실행 시 인천 기준으로 계산해 near/far를 자동 분류한다(geo.trip_window).
좌표는 기후 조회용이라 공항이 아니라 도시 중심 기준이면 충분하다.
min_days/max_days를 채우면 거리 규칙 대신 그 값을 쓴다(기본은 비워 둠).
"""
from __future__ import annotations

from dataclasses import dataclass, field

import geo


@dataclass(frozen=True)
class Destination:
    iata: str
    name_ko: str
    country_ko: str
    lat: float
    lon: float
    min_days: int | None = None
    max_days: int | None = None
    tags: tuple[str, ...] = field(default_factory=tuple)

    @property
    def distance_km(self) -> float:
        return geo.distance_from_origin(self.lat, self.lon)

    @property
    def window(self) -> tuple[int, int, str]:
        lo, hi, tier = geo.trip_window(self.distance_km)
        if self.min_days is not None:
            lo = self.min_days
        if self.max_days is not None:
            hi = self.max_days
        return lo, hi, tier

    @property
    def label(self) -> str:
        return f"{self.name_ko}({self.country_ko})"


